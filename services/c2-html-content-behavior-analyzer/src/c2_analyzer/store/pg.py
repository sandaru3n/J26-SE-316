"""PostgreSQL connection + schema migrations for the C2 results store.

Part 9: Batch B-2 - results store, PostgreSQL backend (optional).

Used when ``DATABASE_URL`` (postgresql://...) is set; otherwise the store stays on the
SQLite file (db.py). Same three tables, with PostgreSQL types: TIMESTAMPTZ instead of
ISO text, JSONB instead of JSON text, BOOLEAN demo flag, BIGINT identity ids.

Why psycopg 3 and not SQLAlchemy (viva): the repository is ~25 hand-written SQL
statements; with psycopg they stay the same text for both databases ('?' becomes '%s')
and only three spots differ (row locking, the version table, the type adapters below).
SQLAlchemy Core would mean rewriting every query for a portability we do not need.

Migrations: ``PG_MIGRATIONS[i]`` turns schema version i into i + 1; applied versions
are rows of ``c2_schema_migrations``. ``migrate`` runs in ONE transaction under a
transaction-level advisory lock, so two processes starting at once never both apply a
step, and running it again (or on every start) changes nothing. Never edit a released
step - append a new one.

Secrets: the connection string is never logged or put in an error message
(``safe_error``); errors name only the exception and PostgreSQL's own reason.
"""

from __future__ import annotations

from datetime import UTC
from urllib.parse import unquote, urlsplit

PG_MIGRATIONS: tuple[str, ...] = (
    # 0 -> 1: jobs, results, review queue (= SQLite v1) + indexes for the /scans filters
    """
    CREATE TABLE IF NOT EXISTS scan_jobs (
        id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        url             TEXT NOT NULL,
        normalized_url  TEXT,
        source          TEXT NOT NULL CHECK (source IN
                          ('user', 'threatradar_push', 'threatradar_pull', 'api')),
        source_ref      JSONB NOT NULL DEFAULT '{}'::jsonb,
        status          TEXT NOT NULL CHECK (status IN
                          ('queued', 'running', 'done', 'failed', 'skipped_duplicate')),
        attempts        INTEGER NOT NULL DEFAULT 0,
        created_at      TIMESTAMPTZ NOT NULL,
        started_at      TIMESTAMPTZ,
        finished_at     TIMESTAMPTZ,
        error           TEXT,
        next_attempt_at TIMESTAMPTZ,
        duplicate_of    BIGINT REFERENCES scan_jobs(id),
        demo            BOOLEAN NOT NULL DEFAULT FALSE
    );
    CREATE INDEX IF NOT EXISTS ix_jobs_queue ON scan_jobs (status, next_attempt_at, id);
    CREATE INDEX IF NOT EXISTS ix_jobs_url ON scan_jobs (normalized_url, finished_at);
    CREATE INDEX IF NOT EXISTS ix_jobs_created ON scan_jobs (created_at);
    CREATE INDEX IF NOT EXISTS ix_jobs_source ON scan_jobs (source, id);
    CREATE INDEX IF NOT EXISTS ix_jobs_duplicate_of ON scan_jobs (duplicate_of)
        WHERE duplicate_of IS NOT NULL;

    CREATE TABLE IF NOT EXISTS scan_results (
        job_id           BIGINT PRIMARY KEY REFERENCES scan_jobs(id) ON DELETE CASCADE,
        analysis_id      TEXT NOT NULL,
        verdict          TEXT,
        threat_class     TEXT,
        risk_score       INTEGER,
        status           TEXT NOT NULL,
        final_url_domain TEXT,
        page_language    TEXT,
        top_findings     JSONB NOT NULL DEFAULT '[]'::jsonb,
        full_response    JSONB NOT NULL,
        created_at       TIMESTAMPTZ NOT NULL
    );
    CREATE INDEX IF NOT EXISTS ix_results_created ON scan_results (created_at);
    CREATE INDEX IF NOT EXISTS ix_results_verdict ON scan_results (verdict, job_id);
    CREATE INDEX IF NOT EXISTS ix_results_class ON scan_results (threat_class, job_id);

    CREATE TABLE IF NOT EXISTS review_queue (
        job_id        BIGINT PRIMARY KEY REFERENCES scan_jobs(id) ON DELETE CASCADE,
        reason        TEXT NOT NULL,
        state         TEXT NOT NULL DEFAULT 'pending'
                        CHECK (state IN ('pending', 'confirmed', 'rejected')),
        decided_label TEXT,
        decided_by    TEXT,
        decided_at    TIMESTAMPTZ,
        exported_at   TIMESTAMPTZ,
        created_at    TIMESTAMPTZ NOT NULL
    );
    CREATE INDEX IF NOT EXISTS ix_review_state ON review_queue (state, created_at);
    """,
)

PG_SCHEMA_VERSION = len(PG_MIGRATIONS)
TABLES = ("scan_jobs", "scan_results", "review_queue")
# pg_advisory_xact_lock key ("C2RS" = C2 results store): serializes concurrent migrations.
_MIGRATION_LOCK = 0x43325253


def is_postgres_url(target: object) -> bool:
    return isinstance(target, str) and target.split("://", 1)[0].lower() in (
        "postgresql",
        "postgres",
    )


def describe_target(url: str) -> str:
    """'database "c2" on localhost:5432' - for messages; no user name, never a password."""
    parts = urlsplit(url)
    name = unquote(parts.path.lstrip("/")) or "(default)"
    host = parts.hostname or "localhost"
    return f'database "{name}" on {host}:{parts.port or 5432}'


def safe_error(error: BaseException, url: str) -> str:
    """First line of a driver error with the connection string / password removed."""
    text = (str(error).strip().splitlines() or [""])[0]
    password = urlsplit(url).password
    for secret in (url, password, unquote(password) if password else None):
        if secret:
            text = text.replace(secret, "***")
    return f"{type(error).__name__}: {text}" if text else type(error).__name__


def configure(connection) -> None:
    """Make rows look like SQLite rows: timestamps as the store's ISO text, JSON as text.

    The repository's code (and every caller) then works unchanged on both backends.
    """
    from psycopg.types.datetime import TimestamptzLoader
    from psycopg.types.string import TextLoader

    from c2_analyzer.store.repository import iso

    class IsoTimestamptzLoader(TimestamptzLoader):
        def load(self, data):
            return iso(super().load(data).astimezone(UTC))

    connection.adapters.register_loader("timestamptz", IsoTimestamptzLoader)
    connection.adapters.register_loader("jsonb", TextLoader)
    connection.execute("SET TIME ZONE 'UTC'")


def connect(url: str, connect_timeout: int = 5):
    """One autocommit connection with the store's adapters (migrations, copy script)."""
    import psycopg
    from psycopg.rows import dict_row

    connection = psycopg.connect(
        url, autocommit=True, row_factory=dict_row, connect_timeout=connect_timeout
    )
    configure(connection)
    return connection


def migrate(connection) -> int:
    """Apply every missing step (one transaction, advisory lock); returns the version."""
    with connection.transaction():
        connection.execute("SELECT pg_advisory_xact_lock(%s)", (_MIGRATION_LOCK,))
        connection.execute(
            "CREATE TABLE IF NOT EXISTS c2_schema_migrations ("
            "version INTEGER PRIMARY KEY, applied_at TIMESTAMPTZ NOT NULL DEFAULT now())"
        )
        row = connection.execute(
            "SELECT COALESCE(MAX(version), 0) AS v FROM c2_schema_migrations"
        ).fetchone()
        current = row["v"]
        if current > PG_SCHEMA_VERSION:
            raise RuntimeError(
                f"results database schema v{current} is newer than this code "
                f"(v{PG_SCHEMA_VERSION})"
            )
        for version in range(current, PG_SCHEMA_VERSION):
            for statement in _statements(PG_MIGRATIONS[version]):
                connection.execute(statement)
            connection.execute(
                "INSERT INTO c2_schema_migrations (version) VALUES (%s)", (version + 1,)
            )
    return PG_SCHEMA_VERSION


def _statements(script: str) -> list[str]:
    """Split a migration script into statements (no ';' or '--' inside our literals)."""
    lines = [line.split("--", 1)[0] for line in script.splitlines()]
    return [part.strip() for part in "\n".join(lines).split(";") if part.strip()]
